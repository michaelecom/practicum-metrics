package adapter

// HTTPServer - общий интерфейс для HTTP серверов
//
// Этот интерфейс позволяет абстрагироваться от конкретной реализации HTTP сервера
// (стандартный net/http, Gin, Chi и т.д.) и легко переключаться между ними.
type HTTPServer interface {
	// Start запускает HTTP сервер на указанном адресе
	//
	// Блокирующий вызов - сервер работает до остановки или ошибки
	Start(addr string) error
}
